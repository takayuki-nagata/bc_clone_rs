//! Writes `docs/VERIFICATION_INVENTORY.md`. A verification tool, checked by tests. The document
//! has no line numbers, so that moving code does not change it.

use crate::Report;
use crate::rules::*;
use crate::scan::{CRATES, Item, WHY_WORDS};
use std::collections::BTreeMap;
use std::fmt::Write;

/// The name of each tier (`TIER_*`).
pub const TIER_NAMES: [&str; TIER_COUNT] = [
    "Verus",
    "Verus (partial)",
    "proof/spec",
    "assumed",
    "bridge",
    "Kani",
    "Miri",
    "shim",
    "uncovered",
    "assume/admit",
];

/// The name of each kind (`KIND_*`).
pub const KIND_NAMES: [&str; 13] = [
    "verified",
    "verified (partial)",
    "proof/spec",
    "`external_body` with a contract",
    "`external_body`",
    "axiom",
    "`assume_specification`",
    "uninterpreted spec",
    "opaque type",
    "external type",
    "`macro_rules!`",
    "outside `verus!`",
    "`assume`/`admit` call",
];

/// What a violation (`V_*`) means.
pub fn violation_text(v: u8) -> &'static str {
    match v {
        V_UNCOVERED => "not covered by Verus, Kani, Miri or a shim (add a `// coverage:` tag)",
        V_TAG_ON_VERIFIED => "a `// coverage:` tag on an item Verus checks",
        V_ASSUMED_OUTSIDE_TRUSTED => "an assumption outside a `trusted*` file",
        V_WRAPPER_UNTESTED => "a trusted wrapper without a Kani harness or Miri test that runs it",
        V_CORE_PLACEMENT => {
            "a bc_core function outside Verus, outside an `unverified*` or `trusted*` file"
        }
        V_WHY => "no valid `why:` reasons",
        V_TARGETS => {
            "a harness, test or integration test of the tag is missing or does not mention the function"
        }
        V_SHIM_BRANCHES => "a shim with a branch",
        V_ASSUME_CALL => "a call of `assume` or `admit`",
        V_MALFORMED_TAG => "a malformed `// coverage:` tag",
        _ => "",
    }
}

fn role_name(role: u8) -> &'static str {
    match role {
        ROLE_CORE => "engine",
        ROLE_PRODUCT => "product",
        ROLE_SPEC => "specification",
        _ => "tool",
    }
}

fn targets(it: &Item) -> String {
    it.tag
        .targets
        .iter()
        .map(|t| format!("`{t}`"))
        .collect::<Vec<_>>()
        .join(", ")
}

/// The document.
pub fn render(r: &Report) -> String {
    let mut s = String::new();
    let _ = writeln!(s, "# Verification inventory\n");
    let _ = writeln!(
        s,
        "<!-- Generated by `cargo run -p bc_inventory`; do not edit. `cargo run -p bc_inventory -- --check` fails when it is out of date. -->\n"
    );
    let _ = writeln!(
        s,
        "Every production function of the workspace and the examples belongs to one tier. Verus is used wherever it can be; \
a function it cannot verify is covered by a Kani harness if possible, otherwise by tests run under Miri; an entry point \
that none of them can run is a branch-free shim, run by an integration test. A function outside Verus carries a \
`// coverage:` comment naming what covers it and why a higher tier cannot (`why:` {}). The rules are `spec fn`s in \
`crates/bc_inventory/src/rules.rs`, verified by Verus; tests, Kani harnesses, the executable specification and this \
tool's reader and writer are verification tools and are only counted. `--check` enforces the rules for the engine, \
the specification and this tool; the front ends' violations are listed below until each front end is brought into the tiers.\n",
        WHY_WORDS
            .iter()
            .map(|w| format!("`{w}`"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let _ = writeln!(s, "| Tier | What it establishes |\n|---|---|");
    let _ = writeln!(
        s,
        "| Verus | The function meets its specification for all inputs (partial correctness where marked) |"
    );
    let _ = writeln!(
        s,
        "| assumed | Verus takes it as true: an axiom, a trusted wrapper or a model; kept in `trusted*` files, and a wrapper's body is run by a test |"
    );
    let _ = writeln!(
        s,
        "| Kani | No panic, overflow or failed assertion for the symbolic inputs of the harness, within its bounds |"
    );
    let _ = writeln!(
        s,
        "| Miri | No undefined behavior or leak on the paths the tests run; functional correctness only as far as the tests assert |"
    );
    let _ = writeln!(
        s,
        "| shim | No branch (checked by this tool); run by the named integration test |\n"
    );

    let _ = writeln!(s, "## Summary\n");
    let shown = [
        TIER_VERUS,
        TIER_VERUS_PARTIAL,
        TIER_ASSUMED,
        TIER_KANI,
        TIER_MIRI,
        TIER_SHIM,
        TIER_UNCOVERED,
        TIER_PROOF,
        TIER_BRIDGE,
        TIER_ASSUME_CALL,
    ];
    let _ = write!(s, "| Crate | Role |");
    for t in shown {
        let _ = write!(s, " {} |", TIER_NAMES[usize::from(t)]);
    }
    let _ = write!(s, "\n|---|---|");
    for _ in shown {
        let _ = write!(s, "---:|");
    }
    let _ = writeln!(s);
    for (k, c) in CRATES.iter().enumerate() {
        let _ = write!(s, "| `{}` | {} |", c.name, role_name(c.role));
        for t in shown {
            let _ = write!(
                s,
                " {} |",
                r.counts
                    .get(k)
                    .and_then(|v| v.get(usize::from(t)))
                    .copied()
                    .unwrap_or(0)
            );
        }
        let _ = writeln!(s);
    }
    let _ = writeln!(s);

    // Functions outside Verus, of the engine and the products.
    let _ = writeln!(s, "## Functions outside Verus\n");
    let mut any = false;
    for (k, c) in CRATES.iter().enumerate() {
        if c.role != ROLE_CORE && c.role != ROLE_PRODUCT {
            continue;
        }
        let rows: Vec<usize> = (0..r.items.len())
            .filter(|&i| {
                r.items[i].krate == k
                    && matches!(
                        r.tiers[i],
                        TIER_KANI | TIER_MIRI | TIER_SHIM | TIER_UNCOVERED
                    )
            })
            .collect();
        if rows.is_empty() {
            continue;
        }
        any = true;
        let _ = writeln!(
            s,
            "### `{}`\n\n| Function | File | Tier | Covered by | Why |\n|---|---|---|---|---|",
            c.name
        );
        for i in rows {
            let it = &r.items[i];
            let _ = writeln!(
                s,
                "| `{}` | `{}` | {} | {} | {} |",
                it.name,
                it.file,
                TIER_NAMES[usize::from(r.tiers[i])],
                targets(it),
                it.tag.why.join(", ")
            );
        }
        let _ = writeln!(s);
    }
    if !any {
        let _ = writeln!(s, "None.\n");
    }

    let _ = writeln!(s, "## Assumptions\n");
    let rows: Vec<usize> = (0..r.items.len())
        .filter(|&i| r.tiers[i] == TIER_ASSUMED)
        .collect();
    if rows.is_empty() {
        let _ = writeln!(s, "None.\n");
    } else {
        let _ = writeln!(
            s,
            "| Crate | Item | File | Kind | Tested by |\n|---|---|---|---|---|"
        );
        for i in rows {
            let it = &r.items[i];
            let _ = writeln!(
                s,
                "| `{}` | `{}` | `{}` | {} | {} |",
                CRATES[it.krate].name,
                it.name,
                it.file,
                KIND_NAMES.get(usize::from(it.kind)).copied().unwrap_or(""),
                targets(it)
            );
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "## Partial correctness\n");
    let _ = writeln!(
        s,
        "Verified functions whose termination is not proved (`exec_allows_no_decreases_clause`).\n"
    );
    let mut by_file: BTreeMap<(usize, &str), Vec<&str>> = BTreeMap::new();
    for (i, it) in r.items.iter().enumerate() {
        if r.tiers[i] == TIER_VERUS_PARTIAL {
            by_file
                .entry((it.krate, it.file.as_str()))
                .or_default()
                .push(it.name.as_str());
        }
    }
    if by_file.is_empty() {
        let _ = writeln!(s, "None.\n");
    } else {
        for ((_, file), names) in &by_file {
            let _ = writeln!(
                s,
                "- `{file}`: {}",
                names
                    .iter()
                    .map(|n| format!("`{n}`"))
                    .collect::<Vec<_>>()
                    .join(", ")
            );
        }
        let _ = writeln!(s);
    }

    let _ = writeln!(s, "## Violations\n");
    if r.violations.is_empty() {
        let _ = writeln!(s, "None.");
    } else {
        for &(i, v) in &r.violations {
            let it = &r.items[i];
            let _ = writeln!(
                s,
                "- `{}` `{}` (`{}`): {}",
                CRATES[it.krate].name,
                it.name,
                it.file,
                violation_text(v)
            );
        }
    }
    s
}
